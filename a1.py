# SVG Writer
# ============================================================
class SVGWriter:

    def __init__(
        self,
        bed_w=256.0,
        bed_h=256.0
    ):

        self.elements = []

        self.bed_w = bed_w
        self.bed_h = bed_h


    # --------------------------------------------------------
    # Line
    # --------------------------------------------------------
    def add_line(
        self,
        x1,
        y1,
        x2,
        y2,
        width
    ):

        self.elements.append(
            (
                "line",
                x1,
                y1,
                x2,
                y2,
                width
            )
        )


    # --------------------------------------------------------
    # Circle
    # --------------------------------------------------------
    def add_circle(
        self,
        cx,
        cy,
        radius,
        width
    ):

        self.elements.append(
            (
                "circle",
                cx,
                cy,
                radius,
                width
            )
        )


    # --------------------------------------------------------
    # Save SVG
    # --------------------------------------------------------
    def save(self, filename):

        svg = [

            '<?xml version="1.0" encoding="UTF-8"?>',

            (
                f'<svg '
                f'xmlns="http://www.w3.org/2000/svg" '
                f'width="{self.bed_w}mm" '
                f'height="{self.bed_h}mm" '
                f'viewBox="0 0 {self.bed_w} {self.bed_h}">'
            ),

            (
                f'<rect '
                f'x="0" '
                f'y="0" '
                f'width="{self.bed_w}" '
                f'height="{self.bed_h}" '
                f'fill="white" '
                f'stroke="black"/>'
            )
        ]

        for elem in self.elements:

            if elem[0] == "line":

                _, x1, y1, x2, y2, w = elem

                sy1 = self.bed_h - y1
                sy2 = self.bed_h - y2

                svg.append(
                    (
                        f'<line '
                        f'x1="{x1:.3f}" '
                        f'y1="{sy1:.3f}" '
                        f'x2="{x2:.3f}" '
                        f'y2="{sy2:.3f}" '
                        f'stroke="black" '
                        f'stroke-width="{w:.3f}" '
                        f'stroke-linecap="round"/>'
                    )
                )

            elif elem[0] == "circle":

                _, cx, cy, r, w = elem

                scy = self.bed_h - cy

                svg.append(
                    (
                        f'<circle '
                        f'cx="{cx:.3f}" '
                        f'cy="{scy:.3f}" '
                        f'r="{r:.3f}" '
                        f'fill="none" '
                        f'stroke="black" '
                        f'stroke-width="{w:.3f}"/>'
                    )
                )

        svg.append("</svg>")

        with open(
            filename,
            "w",
            encoding="utf-8"
        ) as f:

            f.write(
                "\n".join(svg)
            )


