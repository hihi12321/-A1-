# ============================================================
# G-code Writer
# ============================================================
class GCodeWriter:

    def __init__(
        self,
        pen_up_z=5.0,
        pen_down_z=0.0,
        draw_speed=800,
        travel_speed=3000
    ):
        self.lines = []

        self.pen_up_z = pen_up_z
        self.pen_down_z = pen_down_z

        self.draw_speed = draw_speed
        self.travel_speed = travel_speed

    # --------------------------------------------------------
    # 新增 G-code
    # --------------------------------------------------------
    def add(self, line):
        self.lines.append(line)

    # --------------------------------------------------------
    # Header
    # --------------------------------------------------------
    def header(
        self,
        bed_temp=0,
        hotend_temp=0,
        auto_home=True,
        bed_level=False,
        level_bounds=None
    ):

        self.add("; ===============================================")
        self.add("; Bambu A1 PCB Pen Plotter")
        self.add("; Generated by PCB Plotter")
        self.add("; ===============================================")

        self.add("G90 ; Absolute positioning")
        self.add("G21 ; Millimeter unit")

        # ----------------------------------------------------
        # 熱床
        # ----------------------------------------------------
        if bed_temp > 0:
            self.add(
                f"M140 S{bed_temp:.0f} ; Set bed temperature"
            )

            self.add(
                f"M190 S{bed_temp:.0f} ; Wait for bed temperature"
            )

        # ----------------------------------------------------
        # 熱端
        # ----------------------------------------------------
        if hotend_temp > 0:
            self.add(
                f"M104 S{hotend_temp:.0f} ; Set nozzle temperature"
            )

            self.add(
                f"M109 S{hotend_temp:.0f} ; Wait for nozzle temperature"
            )

        # ----------------------------------------------------
        # 抬筆
        # ----------------------------------------------------
        self.pen_up()

        # ----------------------------------------------------
        # Auto Home
        # ----------------------------------------------------
        if auto_home:
            self.add("; ===== Auto Home =====")
            self.add("G28")
            self.add("; ===== Auto Home END =====")

        # ----------------------------------------------------
        # Bambu A1 Auto Bed Leveling
        # ----------------------------------------------------
        if bed_level:

            self.add("")
            self.add("; ===============================================")
            self.add("; Bambu A1 AUTO BED LEVELING")
            self.add("; ===============================================")

            # 安全高度
            self.add("G90")
            self.add("G1 Z5 F1200")

            # ------------------------------------------------
            # A1：
            # 關閉 ABL → 執行探測 → 儲存 → 開啟 ABL
            # ------------------------------------------------

            self.add("G29.2 S0 ; Disable ABL during probing")

            if level_bounds:

                min_x, min_y, max_x, max_y = level_bounds

                # A1 安全限制
                min_x = max(0.0, min_x)
                min_y = max(0.0, min_y)

                max_x = min(256.0, max_x)
                max_y = min(256.0, max_y)

                size_x = max_x - min_x
                size_y = max_y - min_y

                if size_x > 0 and size_y > 0:

                    self.add(
                        "; ABL area:"
                    )

                    self.add(
                        f"; X={min_x:.3f} "
                        f"Y={min_y:.3f} "
                        f"I={size_x:.3f} "
                        f"J={size_y:.3f}"
                    )

                    # A1 Auto Bed Leveling
                    self.add(
                        f"G29 A1 "
                        f"X{min_x:.3f} "
                        f"Y{min_y:.3f} "
                        f"I{size_x:.3f} "
                        f"J{size_y:.3f}"
                    )

                else:

                    self.add(
                        "G29 A1 ; Auto bed leveling"
                    )

            else:

                self.add(
                    "G29 A1 ; Auto bed leveling"
                )

            # 等待動作完成
            self.add("M400")

            # 儲存新的 Mesh
            self.add("M500 ; Save bed leveling mesh")

            # 重新啟用 ABL
            self.add("G29.2 S1 ; Enable ABL")

            self.add(
                "; ==============================================="
            )

            self.add(
                "; A1 AUTO BED LEVELING END"
            )

            self.add(
                "; ==============================================="
            )

            # 再次抬筆
            self.pen_up()

        self.add("")


    # --------------------------------------------------------
    # Footer
    # --------------------------------------------------------
    def footer(
        self,
        bed_temp=0,
        hotend_temp=0
    ):

        self.add("")
        self.add("; ===============================================")
        self.add("; END")
        self.add("; ===============================================")

        self.pen_up()

        # 移到方便取件的位置
        self.add(
            "G0 X0 Y220 F3000 ; Move bed for easy removal"
        )

        # 關閉熱床
        if bed_temp > 0:
            self.add("M140 S0")

        # 關閉熱端
        if hotend_temp > 0:
            self.add("M104 S0")

        self.add("M400")
        self.add("; END")


    # --------------------------------------------------------
    # Pen Up
    # --------------------------------------------------------
    def pen_up(self):

        self.add(
            f"G0 Z{self.pen_up_z:.3f} F3000"
        )


    # --------------------------------------------------------
    # Pen Down
    # --------------------------------------------------------
    def pen_down(self):

        self.add(
            f"G1 Z{self.pen_down_z:.3f} F300"
        )


    # --------------------------------------------------------
    # Move
    # --------------------------------------------------------
    def move(self, x, y):

        self.add(
            f"G0 X{x:.3f} Y{y:.3f} F{self.travel_speed:.0f}"
        )


    # --------------------------------------------------------
    # Draw
    # --------------------------------------------------------
    def draw(self, x, y):

        self.add(
            f"G1 X{x:.3f} Y{y:.3f} F{self.draw_speed:.0f}"
        )


    # --------------------------------------------------------
    # Save
    # --------------------------------------------------------
    def save(self, filename):

        with open(
            filename,
            "w",
            encoding="utf-8"
        ) as f:

            f.write(
                "\n".join(self.lines)
            )


